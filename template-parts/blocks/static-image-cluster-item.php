<?php
/**
 * Shared Inspired Gallery image card.
 *
 * @package LTT_Dive_In
 *
 * @var array  $args Card arguments passed by get_template_part().
 */

$image           = $args['image'];
$image_html      = $args['image_html'];
$index           = (int) $args['index'];
$total           = (int) $args['total'];
$inline_detail   = ! empty( $args['inline_detail'] );
$uses_photoswipe = ! empty( $args['uses_photoswipe'] );
$section_id      = (string) $args['section_id'];
$description_id  = $section_id . '-description-' . $index;
?>
<figure class="static-image-cluster__item">
	<a
		class="static-image-cluster__trigger"
		href="<?php echo esc_url( $image['full'] ); ?>"
		data-ltt-photoswipe-trigger
		data-image-index="<?php echo esc_attr( (string) $index ); ?>"
		data-pswp-width="<?php echo esc_attr( (string) $image['width'] ); ?>"
		data-pswp-height="<?php echo esc_attr( (string) $image['height'] ); ?>"
		<?php if ( $uses_photoswipe ) : ?>aria-haspopup="dialog"<?php endif; ?>
		aria-label="<?php echo esc_attr( sprintf( __( 'View image %1$d of %2$d: %3$s', 'ltt-dive-in' ), $index + 1, $total, $image['alt'] ) ); ?>"
		<?php if ( $inline_detail ) : ?>data-inline-action-label="<?php echo esc_attr( sprintf( __( 'Show image details for %s', 'ltt-dive-in' ), $image['title'] ? $image['title'] : $image['alt'] ) ); ?>"<?php endif; ?>
	>
		<?php // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image() and the block's responsive image helper. ?>
		<?php echo $image_html; ?>
		<span class="static-image-cluster__inspired-info" aria-hidden="true">
			<img src="<?php echo esc_url( get_theme_file_uri( 'assets/images/icons/info.svg' ) ); ?>" alt="" />
		</span>
		<?php if ( $inline_detail ) : ?>
			<span class="static-image-cluster__inspired-hover-overlay" aria-hidden="true"></span>
			<?php if ( $image['description'] ) : ?>
				<span class="static-image-cluster__inspired-description" id="<?php echo esc_attr( $description_id ); ?>" data-inspired-card-description><?php echo esc_html( $image['description'] ); ?></span>
			<?php endif; ?>
		<?php endif; ?>
		<span class="static-image-cluster__inspired-title">
			<img src="<?php echo esc_url( get_theme_file_uri( 'assets/images/icons/location.svg' ) ); ?>" alt="" />
			<?php echo esc_html( $image['title'] ); ?>
		</span>
	</a>
</figure>
